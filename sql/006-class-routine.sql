CREATE TABLE IF NOT EXISTS class_routine (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 class_id INT UNSIGNED NOT NULL,
 author_id INT UNSIGNED NOT NULL,
 course VARCHAR(150) NOT NULL,
 code VARCHAR(50) NOT NULL,
 instructor VARCHAR(150) NOT NULL,
 room VARCHAR(100) NOT NULL,
 weekday TINYINT UNSIGNED NOT NULL,
 start_time TIME NOT NULL,
 end_time TIME NOT NULL,
 kind VARCHAR(20) NOT NULL DEFAULT 'Lecture',
 notes VARCHAR(2000) NOT NULL DEFAULT '',
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY routine_class_day (class_id,weekday,start_time),
 CONSTRAINT fk_routine_class FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE RESTRICT,
 CONSTRAINT fk_routine_author FOREIGN KEY (author_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
